#!/usr/bin/env node
/**
 * Scans the photo folder and writes photos.js.
 *
 * Emits plain JS rather than JSON on purpose: the page then runs straight off
 * the filesystem with no server and no network, which is what you want on a
 * laptop plugged into a TV at a venue with unreliable wifi.
 *
 *   node tools/build-manifest.mjs
 */

import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'photos.js');

const EXTENSIONS = new Set([
  '.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif', '.svg'
]);

/** Encode for use in both `img.src` and CSS `url()`, one segment at a time. */
const encodePath = (p) => p.split('/').map(encodeURIComponent).join('/');

function listImages(dir) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) return [];
  return readdirSync(abs, { withFileTypes: true })
    .filter((e) => e.isFile() && !e.name.startsWith('.'))
    .map((e) => e.name)
    .filter((name) => EXTENSIONS.has(extname(name).toLowerCase()))
    // Deterministic order keeps the generated file diff-friendly. Playback
    // shuffles anyway.
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .map((name) => `${dir}/${name}`);
}

let files = listImages('photos');
let source = 'photos';

if (files.length === 0) {
  files = listImages('samples');
  source = 'samples';
  if (files.length) {
    console.warn(
      'photos/ is empty — falling back to the bundled samples/ placeholders.\n' +
      'Drop your own images into photos/ and re-run to use them.'
    );
  }
}

const banner =
  '/* Generated by tools/build-manifest.mjs — do not edit by hand.\n' +
  ` * ${files.length} image${files.length === 1 ? '' : 's'} from ${source}/\n` +
  ' */\n';

const body =
  'window.IMAGEPLAYER_PHOTOS = [\n' +
  files.map((f) => `  ${JSON.stringify(encodePath(f))}`).join(',\n') +
  (files.length ? '\n' : '') +
  '];\n';

writeFileSync(OUT, banner + body);

if (files.length === 0) {
  console.warn('No images found in photos/ or samples/. Wrote an empty manifest.');
} else {
  console.log(`Wrote photos.js — ${files.length} image(s) from ${source}/`);
}
